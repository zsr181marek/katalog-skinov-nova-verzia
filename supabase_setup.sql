
create table if not exists public.catalog_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.catalog_reviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  item_key text not null,
  item_name text not null,
  rating smallint not null check (rating between 1 and 5),
  comment text check (char_length(comment) <= 2000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  admin_reply text check (char_length(admin_reply) <= 2000),
  admin_reply_at timestamptz,
  unique (user_id, item_key)
);

create index if not exists catalog_reviews_item_key_idx
  on public.catalog_reviews(item_key);
create index if not exists catalog_reviews_created_at_idx
  on public.catalog_reviews(created_at desc);

alter table public.catalog_admins enable row level security;
alter table public.catalog_reviews enable row level security;


drop policy if exists "Anyone can read catalog reviews" on public.catalog_reviews;
create policy "Anyone can read catalog reviews"
on public.catalog_reviews for select
to anon, authenticated
using (true);


drop policy if exists "Users can insert own review" on public.catalog_reviews;
create policy "Users can insert own review"
on public.catalog_reviews for insert
to authenticated
with check (auth.uid() = user_id and not exists (
  select 1 from public.catalog_admins a where a.user_id = auth.uid()
));

drop policy if exists "Users can update own review" on public.catalog_reviews;
create policy "Users can update own review"
on public.catalog_reviews for update
to authenticated
using (auth.uid() = user_id and not exists (
  select 1 from public.catalog_admins a where a.user_id = auth.uid()
))
with check (auth.uid() = user_id and not exists (
  select 1 from public.catalog_admins a where a.user_id = auth.uid()
));


drop policy if exists "Admins can update reviews" on public.catalog_reviews;
create policy "Admins can update reviews"
on public.catalog_reviews for update
to authenticated
using (exists (select 1 from public.catalog_admins a where a.user_id = auth.uid()))
with check (exists (select 1 from public.catalog_admins a where a.user_id = auth.uid()));


drop policy if exists "Admins can read own admin role" on public.catalog_admins;
create policy "Admins can read own admin role"
on public.catalog_admins for select
to authenticated
using (auth.uid() = user_id);


create or replace function public.protect_catalog_review_fields()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if exists (select 1 from public.catalog_admins a where a.user_id = auth.uid()) then
   
    new.user_id := old.user_id;
    new.item_key := old.item_key;
    new.item_name := old.item_name;
    new.rating := old.rating;
    new.comment := old.comment;
    new.created_at := old.created_at;
    new.updated_at := old.updated_at;
    return new;
  else
    
    if new.admin_reply is distinct from old.admin_reply
       or new.admin_reply_at is distinct from old.admin_reply_at then
      raise exception 'Only an administrator can edit the administrator reply';
    end if;
    new.user_id := old.user_id;
    new.item_key := old.item_key;
    new.item_name := old.item_name;
    new.rating := old.rating;
    new.created_at := old.created_at;
    new.admin_reply := old.admin_reply;
    new.admin_reply_at := old.admin_reply_at;
    new.updated_at := now();
    return new;
  end if;
end;
$$;

drop trigger if exists protect_catalog_review_fields on public.catalog_reviews;
create trigger protect_catalog_review_fields
before update on public.catalog_reviews
for each row execute function public.protect_catalog_review_fields();

grant select on public.catalog_reviews to anon, authenticated;
grant insert, update on public.catalog_reviews to authenticated;
grant select on public.catalog_admins to authenticated;


